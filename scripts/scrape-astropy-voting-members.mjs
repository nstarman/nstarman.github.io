// Refresh Astropy's active voting-member snapshot from the project team page.
//
// The website uses this small, reviewed list rather than scraping at render
// time. Run this script when the page changes, or let the annual workflow open
// a PR when it detects a new membership list.
//
//   node scripts/scrape-astropy-voting-members.mjs
//   node scripts/scrape-astropy-voting-members.mjs --check

import fs from 'node:fs';

export const SOURCE = 'https://www.astropy.org/team';
const OUT = 'config/astropy-voting-members.json';

const decode = (text) => text
  .replace(/&nbsp;/gi, ' ')
  .replace(/&amp;/gi, '&')
  .replace(/&quot;/gi, '"')
  .replace(/&apos;|&#0*39;/gi, "'")
  .replace(/&#(x[0-9a-f]+|[0-9]+);/gi, (_, value) => String.fromCodePoint(
    value.startsWith('x') ? Number.parseInt(value.slice(1), 16) : Number.parseInt(value, 10),
  ));

const plainText = (html) => decode(html
  .replace(/<[^>]*>/g, ' ')
  .replace(/\s+/g, ' ')
  .trim());

/** Extract just the list under “Active Voting Members”, excluding emeriti. */
export function parseActiveVotingMembers(html) {
  // Astropy adds an anchor link inside headings, so match the heading element
  // first and compare its rendered text rather than assuming bare text.
  const heading = [...html.matchAll(/<h3\b[^>]*>([\s\S]*?)<\/h3>/gi)]
    .find((match) => plainText(match[1]).startsWith('Active Voting Members'));
  if (!heading) throw new Error('Could not find the “Active Voting Members” heading.');

  const afterHeading = html.slice(heading.index + heading[0].length);
  const nextHeading = afterHeading.search(/<h[1-3][^>]*>/i);
  const section = nextHeading === -1 ? afterHeading : afterHeading.slice(0, nextHeading);
  const members = [...section.matchAll(/<li[^>]*>([\s\S]*?)<\/li>/gi)]
    .map((match) => plainText(match[1]))
    .filter(Boolean);

  if (members.length === 0) throw new Error('Found the active-members heading but no member list.');
  return [...new Set(members)].sort((a, b) => a.localeCompare(b));
}

export function documentFor(active, read = new Date().toISOString().slice(0, 10)) {
  return {
    $comment: 'Generated by scripts/scrape-astropy-voting-members.mjs from Astropy’s public team page. '
      + 'Do not edit by hand — the annual workflow opens a PR when this list changes.',
    source: SOURCE,
    read,
    active,
  };
}

async function main() {
  const response = await fetch(SOURCE, {
    headers: { 'User-Agent': 'nstarkman.space voting-member sync (starkman@mit.edu)' },
  });
  if (!response.ok) throw new Error(`Could not fetch ${SOURCE}: HTTP ${response.status}`);

  const active = parseActiveVotingMembers(await response.text());
  const previous = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const previousDocument = previous ? JSON.parse(previous) : null;
  // A successful annual scrape with no membership change should not create a
  // PR merely to advance a date. The Actions run itself is the audit record.
  const unchanged = JSON.stringify(previousDocument?.active) === JSON.stringify(active);
  const read = unchanged ? previousDocument.read : undefined;
  const next = `${JSON.stringify(documentFor(active, read), null, 2)}\n`;

  if (process.argv.includes('--check')) {
    if (next === previous) {
      console.log(`  ok       ${active.length} active voting members, unchanged`);
      return;
    }
    console.log('  Astropy voting members have changed — run:');
    console.log('    node scripts/scrape-astropy-voting-members.mjs');
    process.exitCode = 1;
    return;
  }

  fs.writeFileSync(OUT, next);
  console.log(`  wrote ${OUT}: ${active.length} active voting members`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((error) => {
    console.error(`  error    ${error.message}`);
    process.exitCode = 1;
  });
}
