// Papers that thank him in their acknowledgements — the Assists on
// /publications/, and their authors on the collaborator map.
//
// NASA ADS indexes the full text of arXiv and the journals and splits out the
// acknowledgements as their own field, `ack:`, so "who thanked me" is one query
// rather than a crawl of arXiv's source dumps. Papers he is an author of are
// excluded: those are his publications, and live in data/.
//
//   ADS_TOKEN=… node scripts/collect-acknowledgements.mjs
//
// A token is free from https://ui.adsabs.harvard.edu/user/settings/token.
//
// The file is generated but its `tags` and `exclude` are curated, the way
// config/places.json is: a paper already in the file keeps the tags it has,
// and a new one gets a guess from its title and abstract, to be checked in the
// pull request that adds it. `exclude` holds bibcodes that matched but do not
// mean him.

import fs from 'node:fs';

const OUT = 'config/acknowledgements.json';
const API = 'https://api.adsabs.harvard.edu/v1/search/query';

// Every spelling a colleague has thanked him by. Never the bare surname:
// `ack:Starkman` is mostly Glenn Starkman.
const NAMES = ['Nathaniel Starkman', 'Nathan Starkman', 'Nate Starkman', 'N. Starkman'];
const QUERY = `ack:(${NAMES.map((n) => `"${n}"`).join(' OR ')}) -author:"Starkman, N"`;

// A first guess at the topic, in the vocabulary data/ already uses, so the
// Topics filter on /publications/ catches it. Reviewed in the PR, not trusted.
// ponytail: keyword rules, not a classifier — fine at a handful a year.
const GUESS = [
  [/stream/i, 'streams'],
  [/dark matter|dark compact|subhalo/i, 'dark-matter'],
  [/milky way|\bgalactic\b|\bgaia\b/i, 'milky-way'],
  [/extragalactic|external galax|rotation curve|galaxies/i, 'extragalactic'],
  [/neural|machine learning|generative|normali[sz]ing flow|emulat/i, 'machine-learning'],
  [/\bjax\b/i, 'jax'],
  [/orbit|potential|dynamic|kinematic/i, 'dynamics'],
  [/simulat|n-body/i, 'simulations'],
  [/cosmic microwave|\bcmb\b/i, 'cmb'],
];
const guess = (text) => GUESS.filter(([re]) => re.test(text)).map(([, tag]) => tag);

const token = process.env.ADS_TOKEN;
if (!token) {
  console.error('  ADS_TOKEN is not set — get one at https://ui.adsabs.harvard.edu/user/settings/token');
  process.exit(1);
}

const url = new URL(API);
url.search = new URLSearchParams({
  q: QUERY,
  fl: 'bibcode,title,author,orcid_pub,orcid_user,orcid_other,pubdate,bibstem,doi,identifier,abstract',
  rows: '2000',
  sort: 'date desc',
});
const res = await fetch(url, { headers: { Authorization: `Bearer ${token}` } });
if (!res.ok) throw new Error(`ADS answered ${res.status}: ${await res.text()}`);
const docs = (await res.json()).response.docs;

const prev = fs.existsSync(OUT)
  ? JSON.parse(fs.readFileSync(OUT, 'utf8'))
  : { exclude: [], papers: [] };
const excluded = new Set(prev.exclude);

// ADS gives three ORCID columns, aligned with the author list, '-' for none:
// as published, as claimed by the author, as claimed by someone else.
const orcidAt = (d, i) => [d.orcid_pub, d.orcid_user, d.orcid_other]
  .map((col) => col?.[i]).find((o) => o && o !== '-');

const papers = [];
for (const d of docs) {
  if (excluded.has(d.bibcode)) continue;
  const arxiv = d.identifier?.find((i) => i.startsWith('arXiv:'))?.slice(6);
  const doi = d.doi?.[0];
  // A preprint's bibcode changes when the journal version is merged into it,
  // so the tags are carried over by any identifier the two share.
  const old = prev.papers.find((p) => p.bibcode === d.bibcode
    || (arxiv && p.arxiv === arxiv) || (doi && p.doi === doi));
  const title = d.title?.[0] ?? '';
  papers.push({
    bibcode: d.bibcode,
    ...(arxiv && { arxiv }),
    ...(doi && { doi }),
    title,
    // "2026-05-00" — ADS writes an unknown day as 00, and a month never is.
    date: d.pubdate.slice(0, 7),
    venue: d.bibstem?.[0],
    // Structured like the authors in data/, so the collaborator script reads
    // both the same way.
    authors: (d.author ?? []).map((name, i) => {
      const [family, given] = name.split(/,\s*/);
      const orcid = orcidAt(d, i);
      return { family, ...(given && { given }), ...(orcid && { orcid }) };
    }),
    tags: old?.tags ?? guess(`${title} ${d.abstract ?? ''}`),
    ...(old ? {} : { new: true }),
  });
}

const fresh = papers.filter((p) => p.new);
for (const p of papers) delete p.new;

const doc = {
  $comment:
    'Generated by scripts/collect-acknowledgements.mjs from NASA ADS. Rerun the script '
    + 'rather than editing papers by hand — except `tags`, which the script keeps, and '
    + '`exclude`, bibcodes that matched the query but thank someone else.',
  query: QUERY,
  exclude: prev.exclude,
  papers,
};
fs.writeFileSync(OUT, `${JSON.stringify(doc, null, 2)}\n`);

console.log(`  wrote ${OUT}: ${papers.length} papers acknowledge him`);
for (const p of fresh) console.log(`  new: ${p.bibcode}  [${p.tags.join(', ')}]  ${p.title}`);
