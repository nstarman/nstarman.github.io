// Every open-source repository Nathaniel has a merged pull request in.
//
// Run by .github/workflows/refresh-contributions.yml once a month, and by hand
// when you want to see what has changed:
//
//   node scripts/collect-contributions.mjs           # rewrites config/contributions.json
//   node scripts/collect-contributions.mjs --check    # exits 1 if it would change
//
// The search API caps any one query at 1000 results and there are already
// nearly four thousand merged PRs, so the query is partitioned by period.
// Periods are walked oldest-first with results sorted by creation date, so the
// first time a repository appears is the first contribution to it and nothing
// has to be compared afterwards.

import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const OUT = 'config/contributions.json';
const EXCLUDE = 'config/contributions-exclude.json';
const USER = 'nstarman';

// Wide enough to cover the account, and split where a single year would exceed
// the 1000-result ceiling. Add a period rather than widening one that is full.
const PERIODS = [
  '2015-01-01..2019-12-31', '2020-01-01..2021-12-31',
  '2022-01-01..2022-12-31', '2023-01-01..2023-12-31',
  '2024-01-01..2024-06-30', '2024-07-01..2024-12-31',
  '2025-01-01..2025-12-31', '2026-01-01..2026-12-31',
  '2027-01-01..2027-12-31', '2028-01-01..2028-12-31',
];

const token = process.env.GITHUB_TOKEN
  || execFileSync('gh', ['auth', 'token'], { encoding: 'utf8' }).trim();

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function api(path) {
  for (let attempt = 0; attempt < 4; attempt += 1) {
    const res = await fetch(`https://api.github.com${path}`, {
      headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' },
    });
    if (res.ok) return res.json();
    // 403 here is the secondary rate limit rather than a permissions problem.
    if (res.status === 403 || res.status === 429) { await sleep(20_000); continue; }
    if (res.status === 404) return null;
    throw new Error(`${res.status} ${res.statusText} for ${path}`);
  }
  throw new Error(`gave up on ${path}`);
}

/** repo -> { first, prs }, first being the earliest PR creation date. */
async function discover() {
  const found = new Map();
  for (const period of PERIODS) {
    const q = encodeURIComponent(`author:${USER} type:pr is:merged created:${period}`);
    for (let page = 1; page <= 10; page += 1) {
      const d = await api(`/search/issues?q=${q}&sort=created&order=asc&per_page=100&page=${page}`);
      const items = d?.items ?? [];
      for (const it of items) {
        const repo = it.repository_url.replace('https://api.github.com/repos/', '');
        const rec = found.get(repo) ?? { first: it.created_at.slice(0, 10), prs: 0 };
        rec.prs += 1;
        found.set(repo, rec);
      }
      if (items.length < 100) break;
      await sleep(2500);                      // the search API allows 30/min
    }
    await sleep(2500);
  }
  return found;
}

/** Repos already rendered as a Software card: they are not "also contributed to". */
function alreadyShown() {
  const shown = new Set();
  for (const f of fs.readdirSync('data')) {
    if (!f.endsWith('.json')) continue;
    const r = JSON.parse(fs.readFileSync(`data/${f}`, 'utf8'));
    if (r.type !== 'software') continue;
    for (const l of r.links ?? []) {
      const m = /^https:\/\/github\.com\/([^/]+\/[^/#?]+)/.exec(l.url ?? '');
      if (m) shown.add(m[1].replace(/\/$/, ''));
    }
  }
  return shown;
}

const found = await discover();
const shown = alreadyShown();
const excluded = new Set(JSON.parse(fs.readFileSync(EXCLUDE, 'utf8')).exclude);

const repos = [];
for (const [repo, rec] of [...found].sort()) {
  if (shown.has(repo) || excluded.has(repo)) continue;
  // His own repositories are the Software tiers' business. One that earns a
  // card is shown as a card; one that has not is not an "other contribution".
  if (repo.startsWith(`${USER}/`)) continue;
  const meta = await api(`/repos/${repo}`);
  // A fork is somebody else's project under a different name; the PR against it
  // is already counted against whatever it was forked from.
  if (!meta || meta.fork) continue;
  repos.push({
    repo,
    url: `https://github.com/${repo}`,
    first: rec.first,
    prs: rec.prs,
    description: meta.description ?? null,
    archived: meta.archived || undefined,
  });
}

repos.sort((a, b) => a.first.localeCompare(b.first) || a.repo.localeCompare(b.repo));

const doc = {
  $comment: 'Generated by scripts/collect-contributions.mjs. Do not edit by hand — '
    + `edit ${EXCLUDE} to drop a repository from the list.`,
  source: `merged pull requests authored by ${USER}`,
  repos,
};
const next = `${JSON.stringify(doc, null, 2)}\n`;

if (process.argv.includes('--check')) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (now === next) { console.log(`  ${OUT} is up to date (${repos.length} repositories)`); process.exit(0); }
  const before = now ? new Set(JSON.parse(now).repos.map((r) => r.repo)) : new Set();
  const added = repos.filter((r) => !before.has(r.repo)).map((r) => r.repo);
  console.log(`  ${OUT} is out of date — ${repos.length} repositories`
    + (added.length ? `, new: ${added.join(', ')}` : ''));
  process.exit(1);
}

fs.writeFileSync(OUT, next);
console.log(`  wrote ${OUT}: ${repos.length} repositories`);
