// The Agent Skills on /tools/: every skill registered in nstarman/skills — kept there or living in
// another repository — from its generated index.json (see that repo's AGENTS.md).
//
// Run by .github/workflows/refresh-skills.yml once a week, and by hand:
//
//   node scripts/collect-skills.mjs                      # rewrites config/skills.json
//   SKILLS_REF=<branch> node scripts/collect-skills.mjs  # read another ref of nstarman/skills
//
// A missing or malformed index throws and writes nothing, so a broken registry never empties
// the section.

import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { skillsFromIndex } from './skills-index.mjs';

const OUT = 'config/skills.json';
const REPO = 'nstarman/skills';
const REF = process.env.SKILLS_REF || 'main';
const token = process.env.GITHUB_TOKEN || execFileSync('gh', ['auth', 'token'], { encoding: 'utf8' }).trim();

const res = await fetch(`https://api.github.com/repos/${REPO}/contents/index.json?ref=${encodeURIComponent(REF)}`, {
  headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github.raw+json' },
});
if (!res.ok) throw new Error(`${REPO}@${REF}/index.json: ${res.status}`);
const skills = skillsFromIndex(JSON.parse(await res.text()));

const doc = {
  $comment: 'Generated by scripts/collect-skills.mjs from nstarman/skills index.json. Do not edit by hand.',
  skills,
};
fs.writeFileSync(OUT, `${JSON.stringify(doc, null, 2)}\n`);
console.log(`  wrote ${OUT}: ${skills.length} skills (${skills.filter((s) => s.from).length} from other repositories)`);
