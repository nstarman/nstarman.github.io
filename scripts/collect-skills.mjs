// The Agent Skills on /tools/: one card per skill in nstarman/skills, from the
// card.json beside each SKILL.md (see that repo's AGENTS.md).
//
// Run by .github/workflows/refresh-skills.yml once a week, and by hand:
//
//   node scripts/collect-skills.mjs                    # rewrites config/skills.json
//   SKILLS_REF=<branch> node scripts/collect-skills.mjs  # read another ref (links still go to main)
//
// A skill without a card.json, or a card that is not {name, description}, throws
// and writes nothing, so a broken card never empties the section.

import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const OUT = 'config/skills.json';
const REPO = 'nstarman/skills';
const REF = process.env.SKILLS_REF || 'main';
const token = process.env.GITHUB_TOKEN || execFileSync('gh', ['auth', 'token'], { encoding: 'utf8' }).trim();

async function get(path, accept = 'application/vnd.github+json') {
  const res = await fetch(`https://api.github.com/repos/${REPO}/${path}`, {
    headers: { Authorization: `Bearer ${token}`, Accept: accept },
  });
  if (!res.ok) throw new Error(`${REPO}/${path}: ${res.status}`);
  return accept.endsWith('raw+json') ? res.text() : res.json();
}

const { tree } = await get(`git/trees/${encodeURIComponent(REF)}?recursive=1`);
const paths = new Set(tree.map((t) => t.path));
const dirs = [...paths].filter((p) => /^[^/]+\/SKILL\.md$/.test(p)).map((p) => p.split('/')[0]).sort();
if (!dirs.length) throw new Error(`${REPO}@${REF}: no */SKILL.md`);

const skills = [];
for (const dir of dirs) {
  if (!paths.has(`${dir}/card.json`)) throw new Error(`${dir}: has SKILL.md but no card.json`);
  const card = JSON.parse(await get(`contents/${dir}/card.json?ref=${encodeURIComponent(REF)}`, 'application/vnd.github.raw+json'));
  const keys = Object.keys(card).sort().join();
  if (keys !== 'description,name' || ![card.name, card.description].every((v) => typeof v === 'string' && v.trim())) {
    throw new Error(`${dir}/card.json: want exactly non-empty "name" and "description", got ${keys}`);
  }
  skills.push({ name: card.name, description: card.description, href: `https://github.com/${REPO}/tree/main/${dir}` });
}

const doc = {
  $comment: 'Generated by scripts/collect-skills.mjs. Do not edit by hand.',
  skills,
};
fs.writeFileSync(OUT, `${JSON.stringify(doc, null, 2)}\n`);
console.log(`  wrote ${OUT}: ${skills.length} skills`);
