// Everyone who has ever held a role in the Astropy Project, read from the
// history of the project website's repository.
//
// The live team page (scrape-astropy-voting-members.mjs) lists only today's
// voting members. A collaborator who coordinated the project in 2016 and has
// since stepped back is as much "someone who runs Astropy" as one who sits on
// it now, so this walks every revision of the pages that named people:
//
//   about.html            2013–  "Astropy Project Coordinators"
//   roles.txt             2016–2018  lead/deputy table
//   roles.json            2018–  roles and their people
//   team.rst, about.rst   2026–  Active and Emeritus Voting Members
//
// "Core Package Contributors" is deliberately not read: that is a credits list,
// not a role.
//
//   node scripts/scrape-astropy-team-history.mjs [path/to/astropy.org]
//
// With no path it clones https://github.com/astropy/astropy.org to a temp dir.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const SOURCE = 'https://github.com/astropy/astropy.org';
const OUT = 'config/astropy-team-history.json';

const decode = (s) => s
  .replace(/<[^>]*>/g, ' ')
  .replace(/&nbsp;/gi, ' ').replace(/&quot;/gi, '"').replace(/&#0*39;|&apos;/gi, "'")
  .replace(/&amp;/gi, '&')
  .replace(/\s+/g, ' ').trim();

// "Kelle Cruz (chair)", "Steve Crawford?" -> the name alone; "Unfilled", "?" and
// "All Coordination Committee Members" are not people.
const dropPlaceholders = (names) => names
  .map((n) => n.replace(/\s*\([^)]*\)/g, '').replace(/\?+$/, '').trim())
  .filter((n) => /\p{L}/u.test(n) && !/^(unfilled|none|tbd|all )/i.test(n));

/** `roles.txt`: `Role | Sub-role | Lead | Deputy`, rows continued by a blank role. */
export function parseRolesTxt(text) {
  const out = [];
  let role = '';
  for (const line of text.split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const cells = line.split('|').map((c) => c.trim());
    if (cells.length < 4 || cells[0] === 'Role') continue;
    if (cells[0]) role = cells[0];
    // Names are comma-separated, and one may carry a note after `::`.
    const people = [...cells[2].split(','), ...cells[3].split(',')].map((n) => n.split('::')[0]);
    for (const name of dropPlaceholders(people)) out.push({ name, role });
  }
  return out;
}

/** `roles.json`: `[{ role, people: [...] }]`. */
export function parseRolesJson(text) {
  return JSON.parse(text).flatMap((r) => dropPlaceholders(r.people ?? [])
    .map((name) => ({ name: decode(name), role: r.role })));
}

/** The names under a reStructuredText heading, up to the next one. */
function rstList(text, heading) {
  const lines = text.split('\n');
  const at = lines.findIndex((l, i) => l.trim() === heading && /^[-=~]{3,}$/.test(lines[i + 1] ?? ''));
  if (at === -1) return [];
  const names = [];
  for (const l of lines.slice(at + 2)) {
    if (/^[-=~*]{3,}$/.test(l)) break;
    const m = l.match(/^- (.+)$/);
    if (m) names.push(m[1]);
  }
  return names;
}

export function parseVotingRst(text) {
  return [
    ...dropPlaceholders(rstList(text, 'Active Voting Members')).map((name) => ({ name, role: 'Voting member' })),
    ...dropPlaceholders(rstList(text, 'Emeritus Voting Members')).map((name) => ({ name, role: 'Voting member (emeritus)' })),
  ];
}

/** `about.html`'s list of project coordinators, whatever the heading level. */
export function parseCoordinators(html) {
  const h = html.match(/<h[2-4][^>]*>\s*Astropy Project Coordinat[\s\S]*?<\/h[2-4]>\s*<ul[^>]*>([\s\S]*?)<\/ul>/i);
  if (!h) return [];
  const items = [...h[1].matchAll(/<li[^>]*>([\s\S]*?)(?=<li|<\/li|$)/gi)].map((m) => decode(m[1]));
  return dropPlaceholders(items).map((name) => ({ name, role: 'Project coordinator' }));
}

const SOURCES = [
  ['about.html', parseCoordinators],
  ['roles.txt', parseRolesTxt],
  ['roles.json', parseRolesJson],
  ['team.rst', parseVotingRst],
  ['about.rst', parseVotingRst],
];

/** Fold every (name, role, date) sighting into one record per name. */
export function fold(sightings) {
  const people = new Map();
  for (const { name, role, date } of sightings) {
    const p = people.get(name) ?? { name, roles: new Set(), first: date, last: date };
    p.roles.add(role);
    if (date < p.first) p.first = date;
    if (date > p.last) p.last = date;
    people.set(name, p);
  }
  return [...people.values()]
    .map((p) => ({ ...p, roles: [...p.roles].sort() }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

export function documentFor(people, read = new Date().toISOString().slice(0, 10)) {
  return {
    $comment: 'Generated by scripts/scrape-astropy-team-history.mjs from the history of '
      + 'astropy/astropy.org. Everyone ever named in a project role, voting member or coordinator. '
      + 'Names are as the page printed them; match on surname and first initial. Do not edit by hand.',
    source: SOURCE,
    read,
    people,
  };
}

function main() {
  let repo = process.argv[2];
  if (!repo) {
    repo = path.join(os.tmpdir(), 'astropy.org');
    if (!fs.existsSync(repo)) execFileSync('git', ['clone', '-q', SOURCE, repo], { stdio: 'inherit' });
  }
  const git = (...args) => execFileSync('git', ['-C', repo, ...args],
    { encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] });

  const sightings = [];
  for (const [file, parse] of SOURCES) {
    const revs = git('log', '--all', '--format=%h %ad', '--date=short', '--', file)
      .split('\n').filter(Boolean).map((l) => l.split(' '));
    for (const [hash, date] of revs) {
      let text;
      try { text = git('show', `${hash}:${file}`); } catch { continue; } // deleted in that commit
      for (const s of parse(text)) sightings.push({ ...s, date });
    }
    console.log(`${file}: ${revs.length} revisions`);
  }
  const people = fold(sightings);
  fs.writeFileSync(OUT, `${JSON.stringify(documentFor(people), null, 2)}\n`);
  console.log(`${people.length} people -> ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
