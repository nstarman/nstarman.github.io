// Generates the world outline the collaborator map draws on.
//
// Natural Earth's 110m land polygons (public domain), projected to Equal Earth
// and written out as one SVG path. Run by hand; the result is committed, so
// the site never fetches map data and CI never depends on a tile server —
// see issue #22 for why.
//
//   node scripts/build-worldmap.mjs
//
// Equal Earth (Šavrič, Patterson & Jenny 2018) is equal-area, so no country is
// drawn larger than it is — the point of a map about where people are.

import fs from 'node:fs';

const NE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson';
const SRC = `${NE}/ne_110m_land.geojson`;
// The same source's major lakes: twenty-four of them, 465 points against the
// land's 5143. The Great Lakes and Victoria are most of why — a continent with
// a hole in it reads as a continent, and a solid one reads as a smudge.
const LAKES = `${NE}/ne_110m_lakes.geojson`;
const OUT = 'src/assets/world-equal-earth.json';

const A1 = 1.340264, A2 = -0.081106, A3 = 0.000893, A4 = 0.003796;
const M = Math.sqrt(3) / 2;

/** lon/lat in degrees -> Equal Earth x/y in projection units. */
function project(lon, lat) {
  const l = (lon * Math.PI) / 180;
  const p = (lat * Math.PI) / 180;
  const th = Math.asin(M * Math.sin(p));
  const th2 = th * th, th6 = th2 * th2 * th2;
  const x = (2 * Math.sqrt(3) * l * Math.cos(th))
    / (3 * (9 * A4 * th6 * th2 + 7 * A3 * th6 + 3 * A2 * th2 + A1));
  const y = A4 * th6 * th2 * th + A3 * th6 * th + A2 * th2 * th + A1 * th;
  return [x, y];
}

// The projection's own extents, so the viewBox fits exactly.
const [MAXX] = project(180, 0);
const [, MAXY] = project(0, 90);

const WIDTH = 1000;
const SCALE = WIDTH / (2 * MAXX);
const HEIGHT = Math.round(2 * MAXY * SCALE);

/** Projection units -> SVG user units, y flipped. */
const toSvg = ([x, y]) => [(x + MAXX) * SCALE, (MAXY - y) * SCALE];

/**
 * Douglas–Peucker. 110m data is already coarse, but projecting it leaves long
 * runs of nearly collinear points that cost bytes and draw nothing.
 */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const [ax, ay] = points[0];
  const [bx, by] = points[points.length - 1];
  let worst = 0, at = 0;
  for (let i = 1; i < points.length - 1; i += 1) {
    const [px, py] = points[i];
    const dx = bx - ax, dy = by - ay;
    const len = Math.hypot(dx, dy);
    const d = len === 0 ? Math.hypot(px - ax, py - ay)
      : Math.abs(dy * px - dx * py + bx * ay - by * ax) / len;
    if (d > worst) { worst = d; at = i; }
  }
  if (worst <= tolerance) return [points[0], points[points.length - 1]];
  return [
    ...simplify(points.slice(0, at + 1), tolerance).slice(0, -1),
    ...simplify(points.slice(at), tolerance),
  ];
}

const round = (n) => Math.round(n * 10) / 10;

/** Fetch a Natural Earth layer and return it as one SVG path plus a point count. */
async function layer(url, tolerance) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`could not fetch ${url}: HTTP ${res.status}`);
  const geo = await res.json();
  const rings = [];
  let before = 0;
  for (const f of geo.features) {
    const polys = f.geometry.type === 'Polygon'
      ? [f.geometry.coordinates] : f.geometry.coordinates;
    for (const poly of polys) {
      for (const ring of poly) {
        before += ring.length;
        const pts = simplify(ring.map(([lon, lat]) => toSvg(project(lon, lat))), tolerance);
        // A ring that simplifies to a line encloses nothing worth drawing.
        if (pts.length < 4) continue;
        rings.push(pts);
      }
    }
  }
  const d = rings
    .map((pts) => `M${pts.map(([x, y]) => `${round(x)} ${round(y)}`).join('L')}Z`)
    .join('');
  return { d, rings: rings.length, before, after: rings.reduce((n, r) => n + r.length, 0) };
}

const land = await layer(SRC, 0.7);
// A tighter tolerance for lakes: they are small enough that 0.7 would round
// Erie and Ontario into the same lozenge.
const lakes = await layer(LAKES, 0.25);
const d = land.d;

fs.mkdirSync('src/assets', { recursive: true });
fs.writeFileSync(OUT, `${JSON.stringify({
  $comment: 'Generated by scripts/build-worldmap.mjs from Natural Earth 110m land and '
    + 'lakes (public domain), projected to Equal Earth. Do not edit by hand.',
  projection: 'Equal Earth (Šavrič, Patterson & Jenny 2018)',
  width: WIDTH,
  height: HEIGHT,
  d,
  lakes: lakes.d,
}, null, 2)}\n`);

console.log(`  wrote ${OUT}`);
console.log(`  land  ${land.rings} rings, ${land.before} -> ${land.after} points, `
  + `${(land.d.length / 1024).toFixed(1)} KB`);
console.log(`  lakes ${lakes.rings} rings, ${lakes.before} -> ${lakes.after} points, `
  + `${(lakes.d.length / 1024).toFixed(1)} KB`);
console.log(`  viewBox 0 0 ${WIDTH} ${HEIGHT} (ratio ${(WIDTH / HEIGHT).toFixed(3)})`);
